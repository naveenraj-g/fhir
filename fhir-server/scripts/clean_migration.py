"""
Clean an Alembic autogenerate migration.

Usage:
    python scripts/clean_migration.py <migration.py> <keep_sequence_name|__none__> [shared_enum,shared_enum,...]

* strips the unrelated drift autogenerate adds (CREATE/DROP SEQUENCE for every OTHER resource, the
  questionnaire_response_item foreign key); pass this resource's `<resource>_pub_seq` to keep its own sequence
  (or `__none__` when the migration adds no new resource);
* rewrites every `sa.Enum(...)` as `postgresql.ENUM(..., create_type=False)`, creates each distinct enum at the start
  of upgrade() and drops it at the end of downgrade();
* names listed in the 3rd argument (e.g. subject_reference_type,encounter_reference_type,organization_reference_type)
  are shared PG types: referenced with create_type=False but never created/dropped here.
"""
import re, sys
p, keep_seq = sys.argv[1], sys.argv[2]
shared = set(sys.argv[3].split(',')) if len(sys.argv) > 3 else set()
s = open(p, encoding="utf8").read()
lines = s.split("\n")
out = []
for l in lines:
    if "SEQUENCE" in l and "op.execute" in l and keep_seq not in l:
        continue
    if "questionnaire_response_item" in l and ("create_foreign_key" in l or "drop_constraint" in l):
        continue
    out.append(l)
s = "\n".join(out)

enums = {}


def rep(m):
    vals, name = m.group(1).rstrip(", "), m.group(2)
    enums.setdefault(name, vals)
    return f"postgresql.ENUM({vals}, name='{name}', create_type=False)"


s = re.sub(r"sa\.Enum\(((?:'[^']*',? ?)+)name='([^']+)'\)", rep, s)
if "from sqlalchemy.dialects import postgresql" not in s:
    s = s.replace("import sqlalchemy as sa\n", "import sqlalchemy as sa\nfrom sqlalchemy.dialects import postgresql\n", 1)
create = "".join(f"    postgresql.ENUM({v}, name='{n}').create(op.get_bind(), checkfirst=True)\n" for n, v in enums.items() if n not in shared)
drop = "".join(f"    postgresql.ENUM(name='{n}').drop(op.get_bind(), checkfirst=True)\n" for n in enums if n not in shared)
s = s.replace("def upgrade() -> None:\n    # ### commands auto generated by Alembic - please adjust! ###\n", "def upgrade() -> None:\n" + create, 1)
s = s.rstrip() + "\n" + drop
open(p, "w", encoding="utf8").write(s)
print(len(enums), "enums")
